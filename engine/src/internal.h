// ---- VRAM / palette layout (see docs/architecture.md, "Video memory") ----
// One name per fixed slot. The modules still use their own local defines; the asserts below
// keep this table honest. A screenblock is 2 KB and a charblock 16 KB, so charblock n
// overlaps screenblocks 8n..8n+7.
#define VRAM_CBB_LEVEL     0        // tileset (+ background layer tiles), charblocks 0-1
#define VRAM_CBB_LEVEL_N   2
#define VRAM_CBB_HUD       2        // HUD text, dialogue box, draw_line tiles
#define VRAM_SBB_LEVEL     24       // 512x512 map: 2x2 screenblocks, 24-27
#define VRAM_SBB_LEVEL_N   4
#define VRAM_SBB_DIALOGUE  28
#define VRAM_SBB_BG        29
#define VRAM_SBB_HUD       30
#define VRAM_SBB_DRAW      31
#define VRAM_DRAW_TILE     400      // draw_line tiles 400-511 of VRAM_CBB_HUD
#define VRAM_DRAW_TILES    112
#define VRAM_TILES_PER_CBB 512      // 16 KB / 32 bytes (4bpp)

#define VRAM_PAL_BACKDROP  0        // entries 1-15: draw_line colors
#define VRAM_PAL_TILESET   1        // banks 1-10
#define VRAM_PAL_TILESET_N 10
#define VRAM_PAL_BG        11
#define VRAM_PAL_DLG_FRAME 12
#define VRAM_PAL_DLG_TEXT  13
#define VRAM_PAL_HUD_ALT   14
#define VRAM_PAL_HUD       15

_Static_assert(VRAM_SBB_LEVEL + VRAM_SBB_LEVEL_N <= VRAM_SBB_DIALOGUE, "level map overlaps dialogue SBB");
_Static_assert(VRAM_SBB_DIALOGUE < VRAM_SBB_BG && VRAM_SBB_BG < VRAM_SBB_HUD && VRAM_SBB_HUD < VRAM_SBB_DRAW,
               "screenblocks must be distinct and ascending");
_Static_assert(VRAM_SBB_DRAW < 32, "screenblock out of range");
// Screenblocks are above every charblock that holds tiles (CBB 0..VRAM_CBB_HUD end at SBB 8*(HUD+1)).
_Static_assert(VRAM_SBB_LEVEL >= 8 * (VRAM_CBB_HUD + 1), "a used screenblock overlaps a used charblock");
_Static_assert(VRAM_CBB_LEVEL + VRAM_CBB_LEVEL_N <= VRAM_CBB_HUD, "tileset charblocks overlap the HUD charblock");
_Static_assert(VRAM_DRAW_TILE + VRAM_DRAW_TILES <= VRAM_TILES_PER_CBB, "draw_line tiles do not fit in their charblock");
_Static_assert(VRAM_PAL_TILESET + VRAM_PAL_TILESET_N == VRAM_PAL_BG, "tileset palette banks must end where the background bank starts");
_Static_assert(VRAM_PAL_BG < VRAM_PAL_DLG_FRAME && VRAM_PAL_DLG_FRAME < VRAM_PAL_DLG_TEXT &&
               VRAM_PAL_DLG_TEXT < VRAM_PAL_HUD_ALT && VRAM_PAL_HUD_ALT < VRAM_PAL_HUD && VRAM_PAL_HUD < 16,
               "palette banks must be distinct and below 16");
// The values the modules actually use (text.h) must match this table.
_Static_assert(TEXT_CBB == VRAM_CBB_HUD && TEXT_SBB == VRAM_SBB_HUD, "text.h disagrees with the layout table");

