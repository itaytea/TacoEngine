#define GLYPH_COUNT ((int)(sizeof(font) / sizeof(font[0])))

static u8 glyph_for_char[128];

static int glyph_pixel(const char *rows, int x, int y) {
    if (x < 0 || x >= 5 || y < 0 || y >= 7) return 0;
    return rows[y * 5 + x] == '#';
}

void text_init(void) {
    u32 *dst = CHARBLOCK(TEXT_CBB);
    for (int i = 0; i < 8; i++) dst[i] = 0;  // tile 0 = blank
    for (int g = 0; g < GLYPH_COUNT; g++) {
        u32 *tile = dst + (g + 1) * 8;
        for (int y = 0; y < 8; y++) {
            u32 row = 0;
            for (int x = 0; x < 8; x++) {
                int px = x - 1;  // glyph sits at x=1..5, shadow at +1,+1
                u32 c = 0;
                if (glyph_pixel(font[g].rows, px, y)) c = 1;
                else if (glyph_pixel(font[g].rows, px - 1, y - 1)) c = 2;
                row |= c << (x * 4);
            }
            tile[y] = row;
        }
        unsigned char ch = (unsigned char)font[g].ch;
        glyph_for_char[ch] = (u8)(g + 1);
        if (ch >= 'A' && ch <= 'Z') glyph_for_char[ch + 32] = (u8)(g + 1);
    }
    PAL_BG[TEXT_PAL * 16 + 1] = RGB15(31, 31, 31);
    PAL_BG[TEXT_PAL * 16 + 2] = RGB15(2, 2, 6);
    PAL_BG[TEXT_PAL * 16 + 3] = RGB15(31, 28, 8);   // highlight (yellow)
    // Yellow glyphs reuse the same tiles via palette bank 14
    PAL_BG[14 * 16 + 1] = RGB15(31, 27, 6);
    PAL_BG[14 * 16 + 2] = RGB15(2, 2, 6);
    REG_BG0CNT = BG_PRIO(0) | BG_CBB(TEXT_CBB) | BG_SBB(TEXT_SBB);
    text_clear();
}

void text_clear(void) {
    u16 *map = SCREENBLOCK(TEXT_SBB);
    for (int i = 0; i < 32 * 32; i++) map[i] = 0;
}

void text_clear_row(int y) {
    u16 *map = SCREENBLOCK(TEXT_SBB);
    for (int x = 0; x < 32; x++) map[y * 32 + x] = 0;
}

static void put(int x, int y, const char *s, int pal) {
    u16 *map = SCREENBLOCK(TEXT_SBB);
    for (; *s && x < 30; s++, x++) {
        unsigned char c = (unsigned char)*s;
        if (x < 0) continue;
        map[y * 32 + x] = (c < 128 ? glyph_for_char[c] : 0) | SE_PAL(pal);
    }
}

void text_print(int x, int y, const char *s) { put(x, y, s, TEXT_PAL); }
void text_print_hi(int x, int y, const char *s) { put(x, y, s, 14); }

void text_print_centered(int y, const char *s) {
    int n = 0;
    while (s[n]) n++;
    put((30 - n) / 2, y, s, TEXT_PAL);
}

// Signed integer to string; returns pointer into buf.
char *text_itoa(int v, char *buf) {
    char tmp[12];
    int n = 0, neg = v < 0;
    unsigned u = neg ? (unsigned)(-v) : (unsigned)v;
    do { tmp[n++] = (char)('0' + u % 10); u /= 10; } while (u);
    int i = 0;
    if (neg) buf[i++] = '-';
    while (n) buf[i++] = tmp[--n];
    buf[i] = 0;
    return buf;
}

// Fixed 8.8 value as "-1.75"
char *text_fixed(int v, char *buf) {
    int neg = v < 0;
    unsigned u = neg ? (unsigned)(-v) : (unsigned)v;
    unsigned whole = u >> 8, frac = ((u & 255) * 100 + 128) >> 8;
    if (frac >= 100) { whole++; frac -= 100; }
    char *p = buf;
    if (neg) *p++ = '-';
    text_itoa((int)whole, p);
    while (*p) p++;
    *p++ = '.';
    *p++ = (char)('0' + frac / 10);
    *p++ = (char)('0' + frac % 10);
    *p = 0;
    return buf;
}
